require('dotenv').config();

const express = require('express');
const Anthropic = require('@anthropic-ai/sdk');
const axios = require('axios');

const app = express();
app.use(express.json());

const PORT = process.env.PORT || 3000;

const anthropic = new Anthropic({
  apiKey: process.env.ANTHROPIC_API_KEY,
});

// ── Health check ─────────────────────────────────────────────────────────────

app.get('/health', (req, res) => {
  res.send('server is running');
});

// ── Webhook endpoint ──────────────────────────────────────────────────────────

app.post('/webhook', async (req, res) => {
  try {
    const payload = req.body;

    // Extract contact fields from GHL webhook payload
    const firstName   = payload.first_name   || payload.firstName   || 'there';
    const companyName = payload.company_name  || payload.companyName || payload.company || '';
    const email       = payload.email         || payload.contactEmail || '';
    const tagsArray   = Array.isArray(payload.tags) ? payload.tags : (payload.tags ? String(payload.tags).split(',').map(t => t.trim()) : []);
    const industry    = payload.industry      || tagsArray.find(t => t)     || 'your industry';
    const contactId   = payload.contact_id    || payload.contactId   || payload.id || '';

    if (!email) {
      console.warn('Webhook received with no email address — skipping.');
      return res.status(400).json({ error: 'Missing email address in payload' });
    }

    console.log(`Processing contact: ${firstName} <${email}> — ${companyName}`);

    // ── Generate email with Claude ──────────────────────────────────────────

    const emailBody = await generateEmail({ firstName, companyName, industry });
    console.log('Email generated by Claude:\n', emailBody);

    // ── Send email via GHL API ──────────────────────────────────────────────

    await sendEmailViaGHL({ contactId, email, firstName, emailBody });
    console.log(`Email sent to ${email}`);

    res.json({ success: true, message: `Email sent to ${email}` });

  } catch (err) {
    console.error('Error processing webhook:', err.message);
    res.status(500).json({ error: err.message });
  }
});

// ── Claude email generator ────────────────────────────────────────────────────

async function generateEmail({ firstName, companyName, industry }) {
  const companyContext = companyName ? `at ${companyName}` : '';
  const industryContext = industry && industry !== 'your industry'
    ? `in the ${industry} space`
    : '';

  const prompt = `Write a cold outreach email from a marketing agency to ${firstName} ${companyContext} ${industryContext}.

Rules:
- 4-5 lines maximum
- Sound human and conversational — no corporate fluff
- Reference their company name naturally if provided
- End with a soft call to action asking for a 15 minute call
- Do NOT include a subject line, salutation, or sign-off — just the body copy
- Do NOT use placeholders like [Your Name] or [Agency Name]

Write only the email body now.`;

  const message = await anthropic.messages.create({
    model: 'claude-opus-4-6',
    max_tokens: 300,
    messages: [{ role: 'user', content: prompt }],
  });

  return message.content[0].text.trim();
}

// ── GHL email sender ──────────────────────────────────────────────────────────

async function sendEmailViaGHL({ contactId, email, firstName, emailBody }) {
  const GHL_API_KEY = process.env.GHL_API_KEY;

  if (!GHL_API_KEY) {
    throw new Error('GHL_API_KEY environment variable is not set');
  }

  // GHL v2 — send email to a contact
  // Docs: https://highlevel.stoplight.io/docs/integrations/
  const response = await axios.post(
    'https://services.leadconnectorhq.com/conversations/messages',
    {
      type: 'Email',
      contactId: contactId,
      emailTo: email,
      subject: `Quick question for ${firstName || 'you'}`,
      message: emailBody,
      html: `<p>${emailBody.replace(/\n/g, '<br>')}</p>`,
    },
    {
      headers: {
        Authorization: `Bearer ${GHL_API_KEY}`,
        'Content-Type': 'application/json',
        Version: '2021-04-15',
      },
    }
  );

  return response.data;
}

// ── Start server ──────────────────────────────────────────────────────────────

app.listen(PORT, () => {
  console.log(`Webhook server listening on port ${PORT}`);
});
